export const radians = (degrees) => (degrees * Math.PI) / 180;
// G and nu follow the thesis parameterization; z is the Zener ratio.
export function moduli(G, nu, z) {
  return {
    c11: G * ((2 * (2 + z)) / (1 + z) - (1 - 4 * nu) / (1 - 2 * nu)),
    c12: G * ((2 * z) / (1 + z) - (1 - 4 * nu) / (1 - 2 * nu)),
    c44: (G * 2 * z) / (1 + z),
  };
}
export function validate(c) {
  if (!(c.c44 > 0 && c.c11 - c.c12 > 0 && c.c11 + 2 * c.c12 > 0))
    throw Error("Require C44 > 0, C11 − C12 > 0 and C11 + 2 C12 > 0.");
  return c;
}
export const zener = (c) => (2 * c.c44) / (c.c11 - c.c12);
// Symmetric tensors use [xx, yy, xy]; xy is tensor shear, not engineering shear.
export const stress = (c, e) => [
  c.c11 * e[0] + c.c12 * e[1],
  c.c12 * e[0] + c.c11 * e[1],
  2 * c.c44 * e[2],
];
export const contract = (a, b) => a[0] * b[0] + a[1] * b[1] + 2 * a[2] * b[2];
// Eliminate the equilibrium displacement of one Fourier mode.
// p and q are phase eigenstrains, angle is the modulation NORMAL from x.
export function kernel(c, p, q, angle) {
  const x = Math.cos(angle),
    y = Math.sin(angle),
    sp = stress(c, p),
    sq = stress(c, q);
  // a = sigma^0 n: the traction generated by the unrelaxed eigenstress.
  const ap = [sp[0] * x + sp[2] * y, sp[2] * x + sp[1] * y],
    aq = [sq[0] * x + sq[2] * y, sq[2] * x + sq[1] * y];
  // Q is the acoustic tensor. Its inverse measures available relaxation.
  const q11 = c.c11 * x * x + c.c44 * y * y,
    q22 = c.c44 * x * x + c.c11 * y * y,
    q12 = (c.c12 + c.c44) * x * y,
    det = q11 * q22 - q12 * q12;
  // B = unrelaxed penalty - mechanical relaxation. Cross terms may be negative.
  return (
    contract(p, sq) -
    (ap[0] * (q22 * aq[0] - q12 * aq[1]) +
      ap[1] * (q11 * aq[1] - q12 * aq[0])) /
      det
  );
}
// cos(theta)^2 + t sin(theta)^2 = 0; theta is the unextended LINE.
// atan2 retains the t = 0 limit without dividing by zero.
export function roots(t) {
  return t > 0
    ? []
    : t === 0
      ? [Math.PI / 2]
      : [Math.atan2(1, Math.sqrt(-t)), Math.PI - Math.atan2(1, Math.sqrt(-t))];
}
export const projection = (t, angle) =>
  Math.cos(angle) ** 2 + t * Math.sin(angle) ** 2;
export function sample(fn, count = 180) {
  return Array.from({ length: count }, (value, iterator) => ({
    angle: (iterator * Math.PI) / count,
    value: fn((iterator * Math.PI) / count),
  }));
}
export function minima(points) {
  const values = points.map((p) => p.value),
    lo = Math.min(...values),
    hi = Math.max(...values),
    span = hi - lo;
  if (span < 1e-10 * Math.max(1e-30, Math.abs(lo), Math.abs(hi)))
    return { flat: true, global: [], local: [], lo, hi };
  const local = points.filter(
    (p, i) =>
      p.value <= points[(i + points.length - 1) % points.length].value &&
      p.value <= points[(i + 1) % points.length].value,
  );
  return {
    flat: false,
    global: local.filter((p) => p.value <= lo + span * 1e-5),
    local,
    lo,
    hi,
  };
}

// Mohr coordinates use tensor shear epsilon_nq; engineering shear is twice this.
export function mohrState(t, angle) {
  const centre = (1 + t) / 2,
    radius = Math.abs(1 - t) / 2;
  return {
    centre,
    radius,
    normal: projection(t, angle),
    shear: ((t - 1) * Math.sin(2 * angle)) / 2,
    transverse: Math.sin(angle) ** 2 + t * Math.cos(angle) ** 2,
  };
}
